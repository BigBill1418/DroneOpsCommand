"""ADR-0043 P1 — the parser's ``details`` payload reaches the sidecar tables.

Two tiers.

**Hermetic** — the coercion layer, and the cross-language wire contract. The
payload arrives as JSON over HTTP from a Rust service, which is the classic
place for a silent failure: rename a field on one side, and every column
quietly writes NULL while the import logs success. So the fixture at
``tests/fixtures/parser_details_payload.json`` is **generated by the Rust
test suite** (``cargo test emit_wire_fixture``) and asserted against by both
sides — Rust checks the checked-in copy still matches what it emits, and the
tests here check every key in it lands somewhere real.

**Real-Postgres** (opt-in on ``DOC_TEST_PG_URL``) — drives the actual import
path end to end and counts rows, because "the writer function returned True"
is not evidence that anything was stored.
"""

from __future__ import annotations

