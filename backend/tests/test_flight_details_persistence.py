@pytest.fixture
async def db_session():
    """A session against a freshly built schema on the throwaway Postgres."""
    from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine

    from app.database import Base
    import app.models  # noqa: F401

    engine = create_async_engine(_PG_URL, poolclass=None)
    async with engine.begin() as conn:
        await conn.run_sync(lambda c: Base.metadata.drop_all(bind=c))
        await conn.run_sync(lambda c: Base.metadata.create_all(bind=c))
    maker = async_sessionmaker(engine, expire_on_commit=False)
    async with maker() as session:
        yield session
    await engine.dispose()


async def _count(session, model) -> int:
    from sqlalchemy import func, select

    return (await session.execute(select(func.count()).select_from(model))).scalar()


@pg_integration
@pytest.mark.asyncio
async def test_a_payload_with_details_writes_one_row_and_n_series(db_session, payload):
    from app.routers.flight_library import _build_flight_from_parsed

    flight = await _build_flight_from_parsed(
        db_session, _base_parsed(details=payload), "hash-with-details", "f.txt"
    )
    await db_session.commit()

    assert flight is not None
    assert await _count(db_session, FlightDetails) == 1
    assert await _count(db_session, FlightSeries) == 15

    row = await db_session.get(FlightDetails, flight.id)
    assert row.frame_count == 20
    assert row.photo_count == 2
    assert row.max_altitude_msl_m == 209.0
    assert row.parser_version == payload["parser_version"]
    assert row.crate_version == "0.5.7"
    assert row.first_frame_at == datetime(2025, 9, 5, 0, 0, 0)
    assert row.take_off_altitude_units == "unconfirmed"
    assert row.schema_version == 1
    assert row.generated_at is not None
    # JSONB groups survive the round trip.
    assert [p["state"] for p in row.phases] == ["Hover", "GPSSport"]
    assert row.health["is_vibrating"] == 1
    assert row.config["time_base"] == "date_time"


