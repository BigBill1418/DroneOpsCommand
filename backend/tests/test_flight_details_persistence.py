FIXTURE = Path(__file__).parent / "fixtures" / "parser_details_payload.json"

#: Keys the parser emits that are NOT ``flight_details`` columns. Each is
#: consumed elsewhere or deliberately dropped — enumerated so a genuinely new,
#: unmapped key shows up as a failure instead of vanishing.
NON_COLUMN_KEYS = {
    "series",  # → flight_series rows
}


@pytest.fixture(scope="module")
def payload() -> dict:
    assert FIXTURE.exists(), (
        f"{FIXTURE} is missing — regenerate it from the parser with:\n"
        "  cd flight-parser && DETAILS_FIXTURE_OUT=../backend/tests/fixtures/"
        "parser_details_payload.json cargo test emit_wire_fixture"
    )
    return json.loads(FIXTURE.read_text())


# ── The cross-language wire contract ───────────────────────────────────


def test_every_payload_key_is_a_real_column_or_explicitly_excluded(payload):
    """A field renamed on the Rust side must fail here, loudly.

    Without this the failure mode is: the parser emits ``photoCount``, the
    writer looks for ``photo_count``, finds nothing, writes NULL — and every
    import still logs "Flight details stored". Silent, permanent, and it looks
    exactly like success.
    """
    columns = {c.name for c in FlightDetails.__table__.columns}
    unmapped = set(payload) - columns - NON_COLUMN_KEYS
    assert not unmapped, (
        f"parser emits keys with no flight_details column: {sorted(unmapped)}. "
        "Either add the column, or add the key to NON_COLUMN_KEYS with a "
        "reason."
    )


def test_the_fixture_is_populated_not_a_shell(payload):
    """A fixture of nulls would make every assertion below vacuously true."""
    scalars = {k: v for k, v in payload.items() if k not in NON_COLUMN_KEYS}
    non_null = {k: v for k, v in scalars.items() if v not in (None, [], {})}
    assert len(non_null) >= 40, f"only {len(non_null)} populated fields"
    assert payload["frame_count"] == 20
    assert payload["photo_count"] == 2
    assert len(payload["series"]) == 15


def test_the_payload_covers_every_column_type_the_writer_coerces(payload):
    """The fixture must exercise each coercion branch, or the coercion layer
    is only tested by its unit tests and never by a real payload."""
    values = build_details_values(payload)
    assert isinstance(values["frame_count"], int)
    assert isinstance(values["max_altitude_msl_m"], float)
    assert isinstance(values["is_beginner_mode"], bool)
    assert isinstance(values["parser_version"], str)
    assert isinstance(values["first_frame_at"], datetime)
    assert isinstance(values["phases"], list)
    assert isinstance(values["config"], dict)


def test_rfc3339_timestamps_become_naive_utc(payload):
    """The parser emits ``...+00:00``; every DateTime column in this repo is
    naive UTC. Storing an aware value is the ADR-0017 class of bug."""
    values = build_details_values(payload)
    for column in ("first_frame_at", "last_frame_at"):
        dt = values[column]
        assert isinstance(dt, datetime)
        assert dt.tzinfo is None, f"{column} must be naive UTC"
    assert values["first_frame_at"] == datetime(2025, 9, 5, 0, 0, 0)
    assert values["last_frame_at"] == datetime(2025, 9, 5, 0, 0, 19)


def test_series_rows_are_built_one_per_named_series(payload):
    fid = uuid.uuid4()
    rows = build_series_rows(fid, payload)
    assert len(rows) == 15
    by_name = {r["name"]: r for r in rows}
    assert "t_offset_s" in by_name
    assert by_name["altitude_msl_m"]["unit"] == "m"
    assert by_name["altitude_msl_m"]["precision_dp"] == 1
    assert by_name["battery_current_a"]["unit"] == "A"
    assert by_name["t_offset_s"]["unit"] == "s"
    for row in rows:
        assert row["flight_id"] == fid
        assert row["source"] == "frame"
        assert row["sample_count"] == 20
        assert len(row["values"]) == 20


def test_series_are_index_aligned_to_the_time_base(payload):
    """The read path's alignment guarantee is only true if the write side
    stores equal-length series. Assert it on the real payload."""
    rows = build_series_rows(uuid.uuid4(), payload)
    lengths = {len(r["values"]) for r in rows if r["source"] == "frame"}
    assert lengths == {20}, f"frame series have mismatched lengths: {lengths}"


def test_missing_samples_survive_as_nulls(payload):
    """The parser emits null for a sample the aircraft never reported. If the
    writer coerced those to 0.0 the chart would show 'signal lost' where the
    truth is 'no report' — a different and alarming claim."""
    rows = {r["name"]: r for r in build_series_rows(uuid.uuid4(), payload)}
    downlink = rows["rc_downlink"]["values"]
    assert downlink[0] is None
    assert downlink[1] is None
    assert 0.0 in downlink, "the fixture should also contain a real zero-signal frame"
    assert downlink.count(None) == 2


def test_recorded_limits_arrive_without_commentary(payload):
    """ADR-0029 / ADR-0031: a height limit is data. Nothing in the payload
    may editorialize about it."""
    values = build_details_values(payload)
    assert values["height_limit_m"] == 120.0
    assert values["max_allowed_height_m"] == 500.0
    blob = json.dumps(payload).lower()
    for banned in ("part 107", "part-107", "exceed", "violation", "400 ft"):
        assert banned not in blob


def test_take_off_altitude_arrives_raw_and_flagged(payload):
    """§9 C-1 — carried but never displayed until a second airframe confirms
    the scale."""
    values = build_details_values(payload)
    assert values["take_off_altitude_raw"] == 1938.0
    assert values["take_off_altitude_units"] == "unconfirmed"


# ── Coercion: the payload is remote input ──────────────────────────────


def test_unknown_keys_are_ignored_not_fatal():
    """A newer parser talking to an older backend must degrade, not crash."""
    values = build_details_values({"frame_count": 5, "a_field_from_the_future": 1})
    assert values["frame_count"] == 5
    assert "a_field_from_the_future" not in values


def test_wrong_typed_values_become_null_rather_than_raising():
    values = build_details_values({
        "frame_count": "not a number",
        "max_altitude_msl_m": {"nope": 1},
        "is_beginner_mode": None,
        "first_frame_at": "definitely not a date",
        "phases": "should be a list",
    })
    assert values["frame_count"] is None
    assert values["max_altitude_msl_m"] is None
    assert values["first_frame_at"] is None
    assert values["phases"] is None


def test_out_of_range_integers_become_null_not_a_dataerror():
    """Postgres ``integer`` is 4 bytes and ``smallint`` 2. An i64 from the
    parser that overflows either would raise mid-import; NULL is the honest
    degradation."""
    assert _coerce(2**31, FlightDetails.__table__.c.frame_count.type, "x") is None
    assert _coerce(2**31 - 1, FlightDetails.__table__.c.frame_count.type, "x") == 2**31 - 1
    assert _coerce(40_000, SmallInteger(), "x") is None
    assert _coerce(32_767, SmallInteger(), "x") == 32_767
    assert _coerce(-32_769, SmallInteger(), "x") is None


def test_non_finite_floats_become_null():
    """NaN and inf have no SQL representation and no meaning as a reading."""
    col = FlightDetails.__table__.c.max_altitude_msl_m.type
    assert _coerce(float("nan"), col, "x") is None
    assert _coerce(float("inf"), col, "x") is None
    assert _coerce(-float("inf"), col, "x") is None
    assert _coerce(193.9, col, "x") == 193.9


def test_overlong_strings_are_truncated_to_the_column_width():
    assert _coerce("x" * 100, String(16), "x") == "x" * 16


def test_series_sample_count_is_recomputed_not_trusted():
    """A payload claiming a count that disagrees with its array would make the
    read path's ``sample_count`` a lie."""
    rows = build_series_rows(uuid.uuid4(), {
        "series": [{"source": "frame", "name": "a", "sample_count": 9999, "values": [1, 2, 3]}]
    })
    assert rows[0]["sample_count"] == 3


def test_malformed_series_blocks_are_skipped_individually():
    rows = build_series_rows(uuid.uuid4(), {
        "series": [
            {"source": "frame", "name": "good", "values": [1.0]},
            {"source": 42, "name": "bad_source", "values": [1.0]},
            {"source": "frame", "name": None, "values": [1.0]},
            {"source": "frame", "name": "no_values"},
            {"source": "frame", "name": "values_not_a_list", "values": "nope"},
            "not even a dict",
        ]
    })
    assert [r["name"] for r in rows] == ["good"]


def test_duplicate_series_keys_do_not_violate_the_primary_key():
    """(flight_id, source, name) is the PK. Two blocks with the same key would
    raise on insert and lose the whole details write."""
    rows = build_series_rows(uuid.uuid4(), {
        "series": [
            {"source": "frame", "name": "dup", "values": [1.0]},
            {"source": "frame", "name": "dup", "values": [2.0, 3.0]},
        ]
    })
    assert len(rows) == 1
    assert rows[0]["values"] == [1.0]


def test_an_absurdly_large_series_is_refused():
    """Bounds the memory a remote service can make this process allocate."""
    rows = build_series_rows(uuid.uuid4(), {
        "series": [
            {"source": "frame", "name": "huge", "values": [0.0] * (MAX_SAMPLES_PER_SERIES + 1)},
            {"source": "frame", "name": "fine", "values": [0.0] * 10},
        ]
    })
    assert [r["name"] for r in rows] == ["fine"]


def test_too_many_series_are_capped():
    rows = build_series_rows(uuid.uuid4(), {
        "series": [
            {"source": "frame", "name": f"s{i}", "values": [0.0]}
            for i in range(MAX_SERIES_PER_FLIGHT + 20)
        ]
    })
    assert len(rows) == MAX_SERIES_PER_FLIGHT


def test_a_payload_that_is_not_a_dict_yields_nothing():
    assert build_series_rows(uuid.uuid4(), {"series": "nope"}) == []
    assert build_series_rows(uuid.uuid4(), {}) == []


